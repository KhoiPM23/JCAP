// Offline authoring tool. Runtime uses the generated SQL embedded in the backend.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '../../../..');
const read = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const dataset = read(path.join(dir, '../learning-n5-n3.json')).Dataset;
const sample = read(path.join(dir, '../sample.json'));
const legacySql = fs.readFileSync(path.join(dir, '../localize-n5-food-permission.sql'), 'utf8');
const hash = row => crypto.createHash('sha256').update(JSON.stringify(row)).digest('hex');
const key = row => `${row.SourceKey}:${row.ExternalId}`;
const quote = value => value == null ? 'NULL' : `N'${String(value).replaceAll("'", "''")}'`;
const equal = (column, value) => value == null ? `${column} IS NULL`
  : `${column} COLLATE Latin1_General_100_BIN2 = ${quote(value)} AND DATALENGTH(${column}) = DATALENGTH(${quote(value)})`;
const sources = new Map(dataset.Sources.map(s => [s.Key, s]));
const completed = { Vocabularies: new Map(), Grammars: new Map() };
const previousTranslations = new Map(Object.entries(read(path.join(dir, 'previous-translations.json'))));
const legacy = {};
for (const [kind, table] of [['Vocabularies', 'Vocab'], ['Grammars', 'Grammar']]) {
  const section = legacySql.split(`INSERT INTO #${table} VALUES`)[1].split(';\r\n')[0].split(';\n')[0];
  const ids = [...section.matchAll(/^\s*\(N'([^']+)'/gm)].map(m => m[1]);
  legacy[kind] = new Set(sample[kind].map(key));
  const source = kind === 'Vocabularies' ? 'openjlpt' : 'nihongo-mono';
  ids.forEach(id => legacy[kind].add(`${source}:${id}`));
}

const sql = [
  '-- Generated by Translations/build.mjs. Edit batch JSON, then regenerate.',
  '-- Vietnamese adaptations by JCAP with AI assistance; not independently expert reviewed.',
  '-- Attribution and licenses remain in ../README.md and the source dataset.',
  'SET NOCOUNT ON; SET XACT_ABORT ON; BEGIN TRANSACTION;',
  'DECLARE @Id int, @Matches int, @Parents int = 0, @Examples int = 0, @Skipped int = 0;'
];
const batchSummary = [];
for (const file of fs.readdirSync(path.join(dir, 'batches')).filter(f => f.endsWith('.json')).sort()) {
  const batch = read(path.join(dir, 'batches', file));
  assert.equal(batch.Status, 'reviewed-by-agent', `${file}: only checked batches may be published`);
  assert(['Vocabularies', 'Grammars'].includes(batch.Kind));
  assert(['N5', 'N4', 'N3'].includes(batch.Level));
  assert(batch.Entries.length > 0 && batch.Entries.length <= (batch.Kind === 'Vocabularies' ? 20 : 5));
  const vocab = batch.Kind === 'Vocabularies';
  const singular = vocab ? 'Vocabulary' : 'Grammar';
  const table = batch.Kind;
  const identityFields = vocab ? ['Word', 'Reading', 'JLPTLevel'] : ['Pattern', 'Reading', 'JLPTLevel'];
  const fields = vocab ? ['Meaning', 'PartOfSpeech', 'Explanation', 'UsageNotes']
    : ['Meaning', 'Formation', 'Explanation', 'UsageNotes'];
  const records = new Map(dataset[table].map(r => [key(r), r]));
  let exampleCount = 0;
  for (const entry of batch.Entries) {
    const id = key(entry), source = sources.get(entry.SourceKey), row = records.get(id);
    assert(row && source, `${file}: unknown source identity ${id}`);
    assert.equal(row.JLPTLevel, batch.Level);
    assert.equal(entry.SourceHash, hash(row), `${file}: original record changed: ${id}`);
    assert(!completed[table].has(id) && !legacy[table].has(id), `${file}: duplicate translation ${id}`);
    assert.deepEqual(Object.keys(entry.Fields).sort(), [...fields].sort());
    for (const field of fields) {
      assert(entry.Fields[field] === null || typeof entry.Fields[field] === 'string');
      if (field !== 'UsageNotes') assert(entry.Fields[field]?.trim(), `${id}: missing ${field}`);
    }
    assert(entry.Fields.Meaning.length <= 1000);
    if (vocab) assert(entry.Fields.PartOfSpeech.length <= 100);
    else assert(entry.Fields.Formation.length <= 1000);
    assert.deepEqual(Object.keys(entry.Examples).sort(), row.Examples.map(e => e.ExternalId).sort(), `${id}: examples incomplete`);
    const previous = previousTranslations.get(id);
    if (previous) {
      assert.deepEqual(Object.keys(previous.Fields).sort(), [...fields].sort(), `${id}: incomplete previous fields`);
      assert(Object.keys(previous.Examples).every(exampleId => Object.hasOwn(entry.Examples, exampleId)),
        `${id}: unknown previous example`);
      previousTranslations.delete(id);
    }
    completed[table].set(id, file);
    const match = `FROM ${table} c JOIN ${singular}Sources cs ON cs.${singular}Id = c.Id
JOIN LearningContentSources s ON s.Id = cs.SourceId
WHERE ${equal('s.Name', source.Name)} AND ${equal('s.Version', source.Version)}
AND ${equal('cs.ExternalId', row.ExternalId)}`;
    const matchesFields = values => fields.map(f => equal(`c.${f}`, values[f])).join(' AND ');
    const permittedFields = previous
      ? `((${matchesFields(row)}) OR (${matchesFields(previous.Fields)}))` : matchesFields(row);
    sql.push(`-- ${file}: ${row.ExternalId}`,
      `SELECT @Matches = COUNT(*), @Id = MIN(c.Id) ${match};`,
      `IF @Matches > 1 THROW 51001, 'Ambiguous translation source: ${row.ExternalId.replaceAll("'", "''")}', 1;`,
      `IF @Matches = 1 AND EXISTS (SELECT 1 FROM ${table} c WHERE c.Id = @Id AND ${identityFields.map(f => equal(`c.${f}`, row[f])).join(' AND ')})`,
      'BEGIN',
      `UPDATE c SET ${fields.map(f => `${f} = ${quote(entry.Fields[f])}`).join(', ')}, UpdatedAt = SYSUTCDATETIME()
FROM ${table} c WHERE c.Id = @Id AND ${permittedFields};`,
      'SET @Parents += @@ROWCOUNT;');
    for (const example of row.Examples) {
      const translation = entry.Examples[example.ExternalId];
      const es = sources.get(example.SourceKey);
      assert(typeof translation === 'string' && translation.trim() && translation.length <= 2000);
      assert(es, `${id}: missing example source`);
      // Backfill empty examples or replace an exact published translation that was corrected.
      const previousExample = previous?.Examples[example.ExternalId];
      const emptyExample = "NULLIF(LTRIM(RTRIM(e.VietnameseTranslation)), N'') IS NULL";
      const permittedExample = previousExample === undefined ? emptyExample
        : `(${emptyExample} OR (${equal('e.VietnameseTranslation', previousExample)}))`;
      sql.push(`UPDATE e SET VietnameseTranslation = ${quote(translation)}
FROM ${singular}Examples e JOIN LearningContentSources s ON s.Id = e.SourceId
WHERE e.${singular}Id = @Id AND ${equal('s.Name', es.Name)} AND ${equal('s.Version', es.Version)}
AND ${equal('e.ExternalId', example.ExternalId)} AND ${equal('e.JapaneseText', example.JapaneseText)}
AND ${permittedExample};`,
      'SET @Examples += @@ROWCOUNT;');
      exampleCount++;
    }
    sql.push('END ELSE SET @Skipped += 1;');
  }
  batchSummary.push({ File: file, Kind: batch.Kind, Level: batch.Level, Entries: batch.Entries.length, Examples: exampleCount });
}
assert.equal(previousTranslations.size, 0, 'Previous translations have no matching batch entry');
sql.push('COMMIT;', 'SELECT @Parents AS ContentTranslated, @Examples AS ExamplesTranslated, @Skipped AS MissingOrChangedIdentity;');

// Stable source-order chunks: adding a completed batch never renumbers subsequent work.
const queue = [];
for (const level of ['N5', 'N4', 'N3']) {
  for (const kind of ['Vocabularies', 'Grammars']) {
    const size = kind === 'Vocabularies' ? 20 : 5;
    const rows = dataset[kind].filter(r => r.JLPTLevel === level && !legacy[kind].has(key(r)));
    for (let offset = 0; offset < rows.length; offset += size) {
      const entries = rows.slice(offset, offset + size).map(row => ({
        SourceKey: row.SourceKey, ExternalId: row.ExternalId, Text: row.Word ?? row.Pattern,
        SourceHash: hash(row), File: completed[kind].get(key(row)) ?? null
      }));
      queue.push({ Id: `${level}-${kind === 'Vocabularies' ? 'V' : 'G'}-${String(offset / size + 1).padStart(3, '0')}`,
        Kind: kind, Level: level, Status: entries.every(e => e.File) ? 'completed' : 'pending', Entries: entries });
    }
  }
}
const counts = ['N5', 'N4', 'N3'].flatMap(level => ['Vocabularies', 'Grammars'].map(kind => {
  const rows = dataset[kind].filter(r => r.JLPTLevel === level);
  const before = rows.filter(r => legacy[kind].has(key(r))).length;
  const now = rows.filter(r => completed[kind].has(key(r))).length;
  return { Level: level, Kind: kind, Total: rows.length, PreviouslyLocalized: before, New: now, Pending: rows.length - before - now };
}));
const next = queue.find(b => b.Status === 'pending');
const progress = `# Tiến độ Việt hóa học liệu\n\nTệp được tạo bởi \`node Data/Seeds/LearningContentSample/Translations/build.mjs\`.\n\n` +
  `**Lô tiếp theo: ${next?.Id ?? 'không còn'}.** Danh sách ID và hash nguồn nằm trong \`Data/Seeds/LearningContentSample/Translations/queue.json\`.\n\n` +
  `| Level | Loại | Tổng | Đã có trước | Lô mới đã kiểm tra | Còn lại |\n|---|---|---:|---:|---:|---:|\n` +
  counts.map(c => `| ${c.Level} | ${c.Kind === 'Vocabularies' ? 'Từ vựng' : 'Ngữ pháp'} | ${c.Total} | ${c.PreviouslyLocalized} | ${c.New} | ${c.Pending} |`).join('\n') +
  `\n\n## Các lô mới\n\n` + batchSummary.map(b => `- ${b.File}: ${b.Entries} mục, ${b.Examples} bản dịch ví dụ.`).join('\n') +
  `\n\n## Cách tiếp tục qua các lượt làm việc\n\n` +
  `1. Đọc Translations/README.md và lấy lô pending đầu tiên trong queue.json.\n` +
  `2. Đọc nguyên bản từng ID trong learning-n5-n3.json. Dịch nghĩa, giải thích, cách dùng/cấu trúc và tất cả ví dụ; giữ nguyên chữ Nhật, cách đọc và ID.\n` +
  `3. Lưu JSON theo mẫu lô trước, kiểm tra ngữ cảnh Nhật; ghi nguồn đối chiếu và vấn đề cần lưu ý trong ReviewNotes.\n` +
  `4. Chạy build.mjs rồi kiểm tra SQL trên database thử nghiệm. Chỉ áp dụng sau khi kiểm tra. Cập nhật Translations/verification.md riêng để ghi việc áp dụng DB.\n` +
  `5. Có thể dừng sau mỗi lô hoàn chỉnh; không cần nhớ tiến độ trong chat. Không đánh dấu lô còn thiếu ví dụ là hoàn tất.\n\n` +
  `Các số trên phản ánh bản dịch lưu trong source, không khẳng định mọi DB đã cập nhật. “Đã có trước” là bộ mẫu và đợt food-permission cũ, chưa được rà soát lại trong đợt này. Bản dịch mới do AI biên soạn và tự rà soát, chưa có thẩm định độc lập.\n`;
const outputs = new Map([
  [path.join(dir, 'reviewed.sql'), sql.join('\n') + '\n'],
  [path.join(dir, 'queue.json'), JSON.stringify({ DatasetVersion: dataset.Version, Batches: queue }, null, 2) + '\n'],
  [path.join(root, 'docs/learning-translation-progress.md'), progress]
]);
for (const [file, content] of outputs) {
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n'), content, `Regenerate ${file}`);
  else fs.writeFileSync(file, content, 'utf8');
}
console.log(JSON.stringify({ Batches: batchSummary.length, Counts: counts, Next: next?.Id }, null, 2));
